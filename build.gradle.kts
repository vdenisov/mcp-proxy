tasks.test {
    useJUnitPlatform()
    // StdoutPurityTest launches the packaged jar as a subprocess - the only honest way to assert
    // that nothing but protocol frames reaches the real stdout.
    dependsOn(tasks.shadowJar)
    // LauncherScriptTest runs the scripts from the source tree, and Gradle cannot infer that: without
    // this the task stays UP-TO-DATE after a launcher is edited, and the edit goes untested.
    inputs.dir("scripts").withPropertyName("launcherScripts")
    // DockerImageTest builds the image from build/dist, and the Dockerfile is part of what it tests.
    dependsOn("packageDistribution")
    inputs.file("Dockerfile").withPropertyName("dockerfile")
    // Live tests hit real MCP servers and need credentials; opt in with -PliveTests.
    if (!project.hasProperty("liveTests")) {
        exclude("**/live/**")
    }
    testLogging {
        events("passed", "skipped", "failed")
    }
}

tasks.withType<Jar>().configureEach {
